import pandas as pd
df = pd.read_csv('data/fertilizer_recommendation.csv')
print('=== Dataset Info ===')
print(f'Shape: {df.shape}')
print(f'Attributes: {df.shape[1]}')
print(f'Records: {df.shape[0]}')
print('\n=== Target Classes (Fertilizers) ===')
print(df['Recommended_Fertilizer'].unique().tolist())
print('\n=== Crops ===')
print(df['Crop_Type'].unique().tolist())
print('\n=== Nulls ===')
print(df.isnull().sum().to_dict())
print('\n=== Duplicates ===')
print(df.duplicated().sum())
print('\n=== Dtypes ===')
print(df.dtypes.to_dict())
print('\n=== Describe ===')
print(df.describe().to_string())
print('\n=== Categorical Value Counts ===')
for col in df.select_dtypes(include=['object']).columns:
    print(f'--- {col} ---')
    print(df[col].value_counts().to_dict())
print('\n=== Target Distribution ===')
print(df['Recommended_Fertilizer'].value_counts(normalize=True).to_dict())
